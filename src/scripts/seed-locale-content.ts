// ── Seed Function ────────────────────────────────────────────
async function run() {
  await connectScript("seed-locale-content");
  const db = mongoose.connection.db!;
  console.log("Connected.\n");

  // Seed articles
  for (const article of arArticles) {
    const exists = await db.collection("articles").findOne({ slug: article.slug });
    if (!exists) {
      await db.collection("articles").insertOne({ ...article, createdAt: new Date(), updatedAt: new Date() });
      console.log(`  [AR] Created: ${article.title}`);
    } else {
      console.log(`  [AR] Skipped (exists): ${article.slug}`);
    }
  }

  for (const article of esArticles) {
    const exists = await db.collection("articles").findOne({ slug: article.slug });
    if (!exists) {
      await db.collection("articles").insertOne({ ...article, createdAt: new Date(), updatedAt: new Date() });
      console.log(`  [ES] Created: ${article.title}`);
    } else {
      console.log(`  [ES] Skipped (exists): ${article.slug}`);
    }
  }

  // Seed categories
  for (const cat of arCategories) {
    const exists = await db.collection("categories").findOne({ slug: cat.slug, locale: "ar" });
    if (!exists) {
      await db.collection("categories").insertOne(cat);
      console.log(`  [AR] Created category: ${cat.label}`);
    } else {
      console.log(`  [AR] Skipped category (exists): ${cat.slug}`);
    }
  }

  for (const cat of esCategories) {
    const exists = await db.collection("categories").findOne({ slug: cat.slug, locale: "es" });
    if (!exists) {
      await db.collection("categories").insertOne(cat);
      console.log(`  [ES] Created category: ${cat.label}`);
    } else {
      console.log(`  [ES] Skipped category (exists): ${cat.slug}`);
    }
  }

  const articleCount = await db.collection("articles").countDocuments();
  const catCount = await db.collection("categories").countDocuments();
  console.log(`\nDone. Total articles: ${articleCount}, Total categories: ${catCount}`);

  await mongoose.disconnect();
}

run().catch((err) => { console.error(err); process.exit(1); });
